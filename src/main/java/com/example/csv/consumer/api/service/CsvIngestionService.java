package com.example.csv.consumer.api.service;

import org.apache.commons.csv.CSVFormat;
import org.apache.commons.csv.CSVParser;
import org.apache.commons.csv.CSVRecord;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.web.multipart.MultipartFile;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.Collections;
import java.util.List;
import java.util.Set;
import java.util.regex.Pattern;
import java.util.stream.Collectors;

@Service
public class CsvIngestionService {

    private final JdbcTemplate jdbcTemplate;

    private static final Pattern SAFE_IDENTIFIER = Pattern.compile("^[a-zA-Z0-9_]+$");

    // Reserved SQL keywords that may appear as Moderne CSV headers (like "path", "source", "user")
    // Wrapping identifiers in double quotes or validating them keeps H2 PostgreSQL mode happy.
    public CsvIngestionService(JdbcTemplate jdbcTemplate) {
        this.jdbcTemplate = jdbcTemplate;
    }

    public record IngestionResult(String fileName, String tableName, int rowsInserted) {}

    @Transactional
    public IngestionResult ingestCsv(MultipartFile file, String commandType) throws IOException {
        String originalFilename = file.getOriginalFilename();
        if (originalFilename == null || !originalFilename.toLowerCase().endsWith(".csv")) {
            throw new IllegalArgumentException("Invalid file. Only .csv files are accepted.");
        }

        CSVFormat format = CSVFormat.DEFAULT.builder()
                .setHeader()
                .setSkipHeaderRecord(true)
                .setIgnoreHeaderCase(true)
                .setTrim(true)
                .setIgnoreEmptyLines(true)
                .build();

        try (var reader = new BufferedReader(new InputStreamReader(file.getInputStream(), StandardCharsets.UTF_8));
             var csvParser = new CSVParser(reader, format)) {

            List<String> headers = csvParser.getHeaderNames();
            if (headers.isEmpty()) {
                throw new IllegalArgumentException("CSV file contains no headers.");
            }
            headers.forEach(header -> validateIdentifier(header, "Column header"));

            // 1. Resolve table name from commandType ("build", "run", "sync", etc.) or infer from headers
            String tableName = resolveTableName(commandType, headers, originalFilename);
            validateIdentifier(tableName, "Table name");

            // 2. Dynamically CREATE TABLE IF NOT EXISTS (and add any new columns if CLI upgraded)
            ensureTableAndColumnsExist(tableName, headers);

            List<CSVRecord> records = csvParser.getRecords();
            if (records.isEmpty()) {
                return new IngestionResult(originalFilename, tableName, 0);
            }

            // 3. Batch insert all rows into the resolved table
            String columns = headers.stream()
                    .map(h -> "\"" + h.toLowerCase() + "\"")
                    .collect(Collectors.joining(", "));
            String placeholders = String.join(", ", Collections.nCopies(headers.size(), "?"));
            String insertSql = "INSERT INTO \"%s\" (%s) VALUES (%s)".formatted(tableName, columns, placeholders);

            List<Object[]> batchArgs = records.stream()
                    .map(record -> headers.stream()
                            .map(h -> {
                                String val = record.get(h);
                                return (val == null || val.isBlank()) ? null : val;
                            })
                            .toArray())
                    .toList();

            jdbcTemplate.batchUpdate(insertSql, batchArgs);

            return new IngestionResult(originalFilename, tableName, batchArgs.size());
        }
    }

    private void ensureTableAndColumnsExist(String tableName, List<String> headers) {
        // Create table if it doesn't exist yet (with an auto-incrementing row_id PK + CSV columns as TEXT)
        String columnDefs = headers.stream()
                .map(h -> "\"" + h.toLowerCase() + "\" VARCHAR")
                .collect(Collectors.joining(", "));

        String createTableSql = """
                CREATE TABLE IF NOT EXISTS "%s" (
                    "row_id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    "ingested_at" TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    %s
                )
                """.formatted(tableName, columnDefs);

        jdbcTemplate.execute(createTableSql);

        // Also ensure that if the table already existed with fewer columns, any new CSV columns are added
        for (String header : headers) {
            String alterSql = "ALTER TABLE \"%s\" ADD COLUMN IF NOT EXISTS \"%s\" VARCHAR"
                    .formatted(tableName, header.toLowerCase());
            jdbcTemplate.execute(alterSql);
        }
    }

    private String resolveTableName(String commandType, List<String> headers, String filename) {
        // Priority 1: Explicit command type sent by modw.cmd (-F "type=build")
        if (commandType != null && !commandType.isBlank()) {
            return commandType.trim().toLowerCase();
        }

        // Priority 2: Fallback header inspection if uploaded manually without 'type' param
        Set<String> lowerHeaders = headers.stream().map(String::toLowerCase).collect(Collectors.toSet());
        if (lowerHeaders.contains("buildid") || lowerHeaders.contains("buildoutcome")) {
            return "build";
        }
        if (lowerHeaders.contains("recipe") || lowerHeaders.contains("runid") || lowerHeaders.contains("runoutcome")) {
            return "run";
        }
        if (lowerHeaders.contains("syncoutcome") && !lowerHeaders.contains("buildoutcome")) {
            return "sync";
        }

        // Priority 3: Strip timestamp suffix if filename is trace-20261013... -> "trace" or base filename
        String baseName = filename.substring(0, filename.length() - 4).toLowerCase();
        if (baseName.startsWith("trace-")) {
            return "trace";
        }
        return baseName.replaceAll("[^a-z0-9_]", "_");
    }

    private void validateIdentifier(String identifier, String type) {
        if (!SAFE_IDENTIFIER.matcher(identifier).matches()) {
            throw new IllegalArgumentException(type + " contains invalid characters: " + identifier);
        }
    }
}